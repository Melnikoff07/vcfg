"""Compile gfx700 IR into a validated raw-code header for the plugin ABI.
Usage: python3 gen_shaders.py <llc> <shaders_dir> <out.h>
Reject unsupported ELF layouts/relocations, nonzero entry offsets and spills.
This validates packaging, not PS4 GPU execution or visual correctness.
"""
import argparse
import pathlib
import re
import struct
import subprocess


def text_words(obj):
    def region(off, size):
        if off < 0 or size < 0 or off > len(obj) or size > len(obj)-off:
            raise ValueError('ELF region outside file')
        return obj[off:off+size]
    region(0, 64)
    if obj[:7] != b'\x7fELF\x02\x01\x01':
        raise ValueError('expected ELF64 little-endian v1')
    typ, machine, version = struct.unpack_from('<HHI', obj, 16)
    flags = struct.unpack_from('<I', obj, 48)[0]
    if (typ, machine, version) != (1, 224, 1) or (flags & 0xff) != 0x22:
        raise ValueError('expected relocatable AMDGPU gfx700 ELF')
    shoff = struct.unpack_from('<Q', obj, 40)[0]
    ehsize, _, _, stride, count, strings = struct.unpack_from('<HHHHHH', obj, 52)
    if ehsize != 64 or stride != 64 or not 0 < strings < count <= 4096:
        raise ValueError('unsupported ELF section table')
    region(shoff, stride*count)
    secs = [struct.unpack_from('<IIQQQQIIQQ', obj, shoff+i*stride) for i in range(count)]
    for sec in secs[1:]:
        if sec[1] != 8:  # NOBITS has no file data.
            region(sec[4], sec[5])
    st = secs[strings]
    if st[1] != 3:
        raise ValueError('invalid section string table')
    names = region(st[4], st[5])
    def name(table, offset):
        if offset >= len(table) or table.find(b'\0', offset) < 0:
            raise ValueError('invalid ELF string offset')
        return table[offset:table.index(b'\0', offset)].decode('ascii')
    texts = [i for i,s in enumerate(secs) if name(names,s[0]) == '.text']
    if len(texts) != 1:
        raise ValueError('expected one .text')
    ti = texts[0]; text = secs[ti]
    if text[1] != 1 or text[2]&6 != 6 or not text[5] or text[5]%4:
        raise ValueError('invalid executable .text')
    # Runtime copies only this section and does not perform any ELF linking.
    for i,s in enumerate(secs):
        if s[1] in (4,9) and s[5]:
            raise ValueError('relocations require a linker; refusing raw shader')
        if i != ti and s[2]&2 and s[5]:
            raise ValueError('additional allocated section not copied by runtime')
    mains = []
    for s in secs:
        if s[1] != 2:
            continue
        if s[9] != 24 or s[5]%24 or not 0 < s[6] < count or secs[s[6]][1] != 3:
            raise ValueError('invalid ELF symbol table')
        strings_sec=secs[s[6]]; tab=region(strings_sec[4],strings_sec[5])
        for off in range(s[4],s[4]+s[5],24):
            nm,info,_,section,value,size=struct.unpack_from('<IBBHQQ',obj,off)
            symname=name(tab,nm)
            if symname=='main':
                mains.append((section,value,size,info&15))
            if info&15==2 and section==ti and symname!='main':
                raise ValueError('out-of-line helper requires separate ABI validation')
    if len(mains)!=1 or mains[0][0]!=ti or mains[0][1]!=0 or mains[0][2]>text[5] or mains[0][3]!=2:
        raise ValueError('main must be a function at .text offset zero')
    if not mains[0][2]:
        raise ValueError('empty main')
    raw=region(text[4],text[5])
    return list(struct.unpack('<%dI'%(len(raw)//4),raw))


def stat(asm, *names):
    for n in names:
        m=re.search(r';\s*%s:\s*(\d+)'%re.escape(n),asm)
        if m:
            return int(m[1])
    raise ValueError('missing LLVM statistic: '+', '.join(names))


def resources(nv,ns,nuser,lds,scratch,y):
    if scratch:
        raise ValueError('scratch/spills require a scratch ring')
    if not 1<=nv<=256 or not 1<=ns<=104 or not 0<=nuser<=16 or not 0<=lds<=32768:
        raise ValueError('resource count exceeds conservative gfx700 plugin limits')
    if ((ns+7)//8+1)*8 > 104:
        raise ValueError('baseline SGPR margin exceeds gfx700 register limit')
    vgprs=(nv-1)//4
    sgprs=(ns+7)//8  # Preserve the baseline's deliberate extra SGPR granule.
    # Preserve baseline FLOAT_MODE=0xc0 / DX10_CLAMP, even though LLVM default
    # FloatMode may differ. Changing denormal modes requires hardware tests.
    return vgprs|(sgprs<<6)|(0xc0<<12)|(1<<21), (nuser<<1)|(1<<7)|(int(y)<<8)|(((lds+511)//512)<<15)


def build(llc,sdir,out):
    sizes={}
    sources=sorted(sdir.glob('*.ll'))
    if not sources:
        raise ValueError('no shader sources; refusing an empty successful build')
    lines=['// generated by tools/gen_shaders.py - do not edit','#pragma once','#include <stdint.h>','']
    for ll in sources:
        name=ll.stem
        if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*',name):
            raise ValueError('invalid shader C identifier')
        src=ll.read_text()
        m=re.search(r';\s*user_sgprs=(\d+)\b',src)
        if not m:
            raise ValueError(name+': missing user_sgprs ABI declaration')
        # Mode 8 / velocity kernels use the table-pointer ABI (2 user SGPRs = table pointer). The legacy mode 1..7
        # kernels of the project pass V#s directly in user SGPRs: they are accepted with a note instead of being
        # refused (merged build v1.14; the R7 version stopped the whole build on them). ELF / relocation / scratch
        # checks stay strict for every kernel.
        has_y=bool(re.search(r';\s*tgid_y=1\b',src))
        args='ptr addrspace(4) inreg %tbl, i32 inreg %gx, '+('i32 inreg %gy, ' if has_y else '')+'i32 %tid'
        if int(m[1])!=2 or 'define amdgpu_cs void @main('+args+')' not in src:
            print(f'{name}: note: not the table-pointer ABI (user_sgprs={m[1]}), entry signature not checked')
        asm=subprocess.run([llc,'-mcpu=gfx700','-O2','-filetype=asm',str(ll),'-o','-'],capture_output=True,text=True,check=True).stdout
        obj=subprocess.run([llc,'-mcpu=gfx700','-O2','-filetype=obj',str(ll),'-o','-'],capture_output=True,check=True).stdout
        nv=stat(asm,'NumVgprs'); ns=stat(asm,'TotalNumSgprs','NumSgprs')
        scratch=stat(asm,'ScratchSize'); lds=stat(asm,'LDSByteSize')
        r1,r2=resources(nv,ns,int(m[1]),lds,scratch,has_y)
        words=text_words(obj);words += [0xBF810000]*((-len(words))%64+16)
        sizes[name]=len(words)
        up=name.upper()
        lines += [f'#define {up}_RSRC1 0x{r1:08X}',f'#define {up}_RSRC2 0x{r2:08X}',f'#define {up}_NWORDS {len(words)}',f'static const uint32_t {name}_code[{len(words)}] = {{']
        lines += ['    '+', '.join(f'0x{w:08X}' for w in words[i:i+8])+',' for i in range(0,len(words),8)]
        lines += ['};','']
        print(f'{name}: {len(words)} words, vgprs={nv} sgprs={ns} user={int(m[1])} lds={lds} scratch={scratch} rsrc1={r1:08X} rsrc2={r2:08X}')
    # Build-time region check: the mode-8 + velocity + rcas8/osd8 shaders start at 0x8000 (256 B aligned) and must end below DCB8_OFF (0x1C000)
    used=[n for n in ('pyr8','me3','me2','me1','phase8','warp8','dump8','gm8','fgs8','mf8','gv8','gvc8','warp8g','gvz8','rcas8','osd8') if n in sizes]
    if 'pyr8' in used:
        aligned=sum(((sizes[n]*4+255)&~255) for n in used)
        print(f'shader region: 0x8000 + 0x{aligned:x} = 0x{0x8000+aligned:x} (limit 0x1C000)')
        if 0x8000+aligned>0x1C000: raise SystemExit(f'FATAL: shaders end at 0x{0x8000+aligned:x} > DCB8_OFF 0x1C000')
    # Build completely before replacing a previously valid output header.
    tmp=out.with_name(out.name+'.tmp')
    tmp.write_text('\n'.join(lines)+'\n');tmp.replace(out)


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('llc');p.add_argument('shaders',type=pathlib.Path);p.add_argument('out',type=pathlib.Path)
    a=p.parse_args()
    try:build(a.llc,a.shaders,a.out)
    except ValueError as e:raise SystemExit(str(e))

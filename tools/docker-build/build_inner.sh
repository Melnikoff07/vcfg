#!/bin/bash
# Runs INSIDE the vcfg-build container. Linux port of build.ps1, classic/build.ps1 and launcher/build_pkg.ps1.
#   build_inner.sh <work_src> <out_dir> <pkg_version> <regen_label|-> <run_tests 0|1> [test_shim] [bench 0|1]
# <work_src> is a disposable copy of the source tree; only <work_src>/build and classic/source/{shaders.h,git_ver.h}
# are written there (the same files the official scripts write).
set -euo pipefail
R=$1; OUT=$2; PKGVER=$3; REGEN=$4; TESTS=$5; TEST_SHIM=${6:-}; BENCH=${7:-0}
TC=$OO_PS4_TOOLCHAIN; SDK=/opt/goldhen-sdk; PY=python3
BIN=$TC/bin/linux; PKGTOOL=$BIN/PkgTool.Core
export DOTNET_ROLL_FORWARD=Major
cd "$R"
log() { printf '\n== %s\n' "$*"; }
# PowerShell Get-ChildItem order (case-insensitive by name).
lsort() { for f in "$@"; do printf '%s\n' "$f"; done | LC_ALL=C sort -f; }
VERFILE=$(tr -d '\r\n\t ' < VERSION)                  # build.ps1: (Get-Content VERSION -Raw).Trim()
VERCLASSIC=$(head -n 1 VERSION | tr -cd '0-9.')       # classic/build.ps1: first line, digits and dots
[ "$PKGVER" = "$VERFILE" ] || echo "WARN: PKG version $PKGVER != VERSION file $VERFILE (plugins use VERSION, as the official scripts do)"
COMMON_DEF=(-D_BSD_SOURCE=1 -D__BSD_VISIBLE=1 -D__PS4__=1 -DOO=1 -D__OPENORBIS__=1 -D__OOPS4__=1 -D__FINAL__=1 -D__USE_PRINTF__)
PRXLIBS=(-lSceLibcInternal -lSceGnmDriver -lSceVideoOut -lScePad -lGoldHEN_Hook -lkernel -lSceSysmodule -lSceSystemService -lSceUserService)

# 1. New engine (build.ps1, Target=plugin, release stages).
log "plugin: build/vcfg/vcfg.prx"
S=$R/plugin; B=$R/build/vcfg; mkdir -p "$B"
DEF=("${COMMON_DEF[@]}" -DA21_SLAB2=1 -DA21_POST=1 -DA21_MENU=1 -DA21_SCHED=1 -DA22_UNIVERSAL=1 "-DVCFG_VER=$VERFILE")
INC=(-isysroot "$TC" -isystem "$TC/include" "-I$SDK/include" "-I$S/common" "-I$S/source" "-I$R/overlay")
FL=(--target=x86_64-pc-freebsd12-elf -fPIC -funwind-tables "-ffile-prefix-map=$R=." -Wno-c99-designator -Werror=format)
OBJS=()
while IFS= read -r f; do
  o=$B/$(basename "$f" .c).o
  clang "${FL[@]}" "${DEF[@]}" "${INC[@]}" -c "$f" -o "$o"; OBJS+=("$o")
done < <(lsort "$S"/common/*.c; lsort "$S"/source/*.c; echo "$R/overlay/vov.c")
ld.lld -m elf_x86_64 -pie -e _init --script "$TC/link.x" --eh-frame-hdr -L "$TC/lib" -L "$SDK" "$SDK/build/crtprx.o" "${OBJS[@]}" "${PRXLIBS[@]}" -o "$B/vcfg.elf"
(cd "$B" && "$BIN/create-fself" -in=vcfg.elf -out=vcfg.oelf -lib=vcfg.prx --paid 0x3800000000000011)
log "plugin: elf_arrays (gate in build.ps1)"
$PY -I tools/elf_arrays.py "$B/vcfg.elf" "$S/source"

# 2. Classic engine (classic/build.ps1, Test=0; -Bench with --bench).
H=$R/classic; CLS=classic; [ "$BENCH" = 1 ] && CLS=classic-bench
log "classic: build/$CLS/vcfg_classic.prx"
B=$R/build/$CLS; mkdir -p "$B"
if [ "$REGEN" != "-" ]; then
  echo "shaders.h: regenerated before this step by build_all.sh ($REGEN); see shaders-regen.txt"
else
  echo "shaders.h: versioned header (no regeneration)"
fi
printf '#define GIT_COMMIT "vcfg"\n#define GIT_VER "vcfg"\n#define GIT_NUM 0\n#define BUILD_DATE "vcfg"\n' > "$H/source/git_ver.h"
if [ "$BENCH" = 1 ]; then
  [ -s "$B/bench_shaders.h" ] || { echo "bench: $B/bench_shaders.h missing (generated by build_all.sh --bench)" >&2; exit 1; }
  $PY -I "$H/bench/build_id.py" "$B"                 # classic/build.ps1 -Bench: bench_build.h + bench_sources.json
fi
FL=(--target=x86_64-pc-freebsd12-elf -fPIC -funwind-tables "-ffile-prefix-map=$R=." -isysroot "$TC"
    -isystem "$TC/include" "-I$SDK/include" "-I$H/source" "-I$R/overlay"
    -Wno-c99-designator "${COMMON_DEF[@]}" "-DVCFG_VER=$VERCLASSIC" -DVCFG_2BUF_TEST=0 "-DVCFG_BENCH=$BENCH" "-I$B")
OBJS=()
while IFS= read -r f; do
  o=$B/$(basename "$f" .c).o
  clang "${FL[@]}" -c "$f" -o "$o"; OBJS+=("$o")
done < <(lsort "$H"/source/*.c; echo "$R/overlay/vov.c")
ld.lld "$SDK/build/crtprx.o" "${OBJS[@]}" -o "$B/vcfg_classic.elf" -m elf_x86_64 -pie -e _init --script "$TC/link.x" \
  --eh-frame-hdr "-L$TC/lib" "-L$SDK" "${PRXLIBS[@]}"
(cd "$B" && "$BIN/create-fself" -in=vcfg_classic.elf -out=vcfg_classic.oelf -lib=vcfg_classic.prx --paid 0x3800000000000011)

if [ "$TESTS" = 1 ]; then
  log "regression tests (gate in build.ps1 / classic/build.ps1), llvm_bin shim: $TEST_SHIM"
  # The tests read llvm_bin from config.json and call clang.exe / lli.exe (Windows). The shim maps them to the
  # container's LLVM 18; shim/host also retargets the test bitcode to x86_64-pc-linux-gnu (see report).
  $PY -I -c "import json,sys; c=json.load(open('config.example.json')); c['llvm_bin']=sys.argv[1]; c['python']='python3'; json.dump(c,open('config.json','w'),indent=2)" "$TEST_SHIM"
  $PY -I tools/tests/test_lowmem_valve.py
  $PY -I tools/tests/test_real_traces.py
fi

# 3. Launcher + PKG (launcher/build_pkg.ps1).
log "launcher: build/launcher/VCFG_v$PKGVER.pkg"
L=$R/launcher; B=$R/build/launcher; ST=$B/pkgroot
rm -rf "$ST"; mkdir -p "$ST/sce_sys/about" "$ST/sce_module" "$ST/plugins" "$ST/assets/fonts"
# -ffile-prefix-map and the relative create-fself input are not in build_pkg.ps1: they keep the build path out of
# eboot.bin (as the plugins already do), so the launcher is identical wherever it is built.
FL=(--target=x86_64-pc-freebsd12-elf -fPIC -funwind-tables "-ffile-prefix-map=$R=." -O2 -Wall -Wno-unused-function -Werror=format
    -D_BSD_SOURCE=1 -D__BSD_VISIBLE=1 -D__PS4__=1 -DOO=1 "-DVCFG_VER=$PKGVER" -isysroot "$TC" -isystem "$TC/include" "-I$SDK/include")
OBJS=()
for f in main ui app; do clang "${FL[@]}" -c "$L/src/$f.c" -o "$B/$f.o"; OBJS+=("$B/$f.o"); done
ld.lld -m elf_x86_64 -pie --script "$TC/link.x" --eh-frame-hdr "$TC/lib/crt1.o" "${OBJS[@]}" \
  -L "$TC/lib" -L "$SDK" -lGoldHEN_Hook -lc -lkernel -lSceVideoOut -lScePad -lSceUserService -lSceSysmodule -lSceSystemService \
  -o "$B/launcher.elf"
(cd "$B" && "$BIN/create-fself" -in=launcher.elf -out=launcher.oelf "--eboot=$ST/eboot.bin" --paid 0x3800000000000011)
cp "$R/build/vcfg/vcfg.prx" "$ST/plugins/vcfg16.prx"
cp "$R/build/$CLS/vcfg_classic.prx" "$ST/plugins/vcfg_classic51.prx"
cp "$R/build/$CLS/vcfg_classic.prx" "$ST/plugins/vcfg_alt_16.prx"
cp "$L"/assets/fonts/* "$ST/assets/fonts/"
SAMPLE=$TC/samples/hello_world; [ -f "$SAMPLE/sce_module/libc.prx" ] || SAMPLE=$TC/samples/audio-wav
cp "$SAMPLE/sce_module/libc.prx" "$SAMPLE/sce_module/libSceFios2.prx" "$ST/sce_module/"
cp "$SAMPLE/sce_sys/about/right.sprx" "$ST/sce_sys/about/"
cp "$L/assets/icon0.png" "$ST/sce_sys/icon0.png"
CID=IV0000-VCFG00001_00-VCFGINSTALLER000
SFO=$ST/sce_sys/param.sfo
"$PKGTOOL" sfo_new "$SFO"
while read -r k t m v; do "$PKGTOOL" sfo_setentry "$SFO" "$k" --type "$t" --maxsize "$m" --value "$v"; done <<EOF
APP_TYPE Integer 4 1
APP_VER Utf8 8 $PKGVER
ATTRIBUTE Integer 4 0
CATEGORY Utf8 4 gd
CONTENT_ID Utf8 48 $CID
DOWNLOAD_DATA_SIZE Integer 4 0
SYSTEM_VER Integer 4 0
TITLE Utf8 128 VCFG
TITLE_ID Utf8 12 VCFG00001
VERSION Utf8 8 $PKGVER
EOF
FILES=(eboot.bin sce_sys/param.sfo sce_sys/icon0.png sce_sys/about/right.sprx sce_module/libc.prx sce_module/libSceFios2.prx
       plugins/vcfg16.prx plugins/vcfg_classic51.prx plugins/vcfg_alt_16.prx)
while IFS= read -r f; do FILES+=("assets/fonts/$(basename "$f")"); done < <(lsort "$ST"/assets/fonts/*)
FX=""; for f in "${FILES[@]}"; do FX+="${FX:+$'\n'}  <file targ_path=\"$f\" orig_path=\"$f\" />"; done
cat > "$ST/pkg.gp4" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<psproject fmt="gp4" version="1000">
 <volume><volume_type>pkg_ps4_app</volume_type><volume_id>PS4VOLUME</volume_id><volume_ts>2026-10-19 00:00:00</volume_ts>
 <package content_id="$CID" passcode="00000000000000000000000000000000" storage_type="digital50" app_type="full" />
 <chunk_info chunk_count="1" scenario_count="1"><chunks><chunk id="0" layer_no="0" label="Chunk #0" /></chunks><scenarios default_id="0"><scenario id="0" type="sp" initial_chunk_count="1" label="Scenario #0">0</scenario></scenarios></chunk_info></volume>
 <files img_no="0">
$FX
 </files>
 <rootdir><dir targ_name="sce_sys"><dir targ_name="about" /></dir><dir targ_name="sce_module" /><dir targ_name="plugins" /><dir targ_name="assets"><dir targ_name="fonts" /></dir></rootdir>
</psproject>
EOF
(cd "$ST" && "$PKGTOOL" pkg_build pkg.gp4 "$B")
log "pkg_validate"
"$PKGTOOL" pkg_validate "$B/$CID.pkg"
cp "$B/$CID.pkg" "$B/VCFG_v$PKGVER.pkg"

# 4. Artifacts.
mkdir -p "$OUT"
CNAME=vcfg_classic; [ "$BENCH" = 1 ] && CNAME=vcfg_classic_bench
cp "$R/build/vcfg/vcfg.prx" "$B/VCFG_v$PKGVER.pkg" "$OUT/"
cp "$R/build/$CLS/vcfg_classic.prx" "$OUT/$CNAME.prx"; cp "$R/build/$CLS/vcfg_classic.elf" "$OUT/$CNAME.elf"
cp "$R/build/vcfg/vcfg.elf" "$OUT/"
[ "$BENCH" = 1 ] && cp "$R/build/$CLS/bench_sources.json" "$R/build/$CLS/bench_build.h" "$OUT/"
log "artifacts"
(cd "$OUT" && for f in vcfg.prx "$CNAME.prx" "VCFG_v$PKGVER.pkg"; do printf '%s  %s bytes\n' "$(sha256sum "$f")" "$(stat -c %s "$f")"; done)

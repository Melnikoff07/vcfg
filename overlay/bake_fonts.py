"""Bakes the in-game overlay fonts into overlay/vov_fonts.h (8-bit coverage atlases, no rasterizer in the plugin).
Usage: python -I overlay/bake_fonts.py   (fonts from launcher/assets/fonts, SIL OFL)"""
import pathlib
from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent
FONTS = HERE.parent / 'launcher' / 'assets' / 'fonts'
EXTRA = '\u2190\u2192\u2191\u2193\u2195\u25cb\u00d7\u25b3\u25a1\u00b7\u203a'   # arrows, circle, cross, triangle, square, dot, chevron
ASCII = ''.join(chr(c) for c in range(32, 127))
FACES = [  # name, file, pixel size, characters
    ('mono20', 'JetBrainsMono-Medium.ttf', 20, ASCII + EXTRA),
    ('text25', 'Inter-Medium.ttf', 25, ASCII + '\u203a'),
    ('big84', 'InterDisplay-Medium.ttf', 84, '0123456789.-'),
    ('big40', 'InterDisplay-Medium.ttf', 40, '0123456789.-'),
]

def bake(name, file, px, chars):
    font = ImageFont.truetype(str(FONTS / file), px)
    asc, desc = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in chars:
        l, t, r, b = font.getbbox(ch, anchor='ls')
        w, h = max(r - l, 0), max(b - t, 0)
        adv = round(font.getlength(ch))
        off = len(data)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255, anchor='ls')
            data += im.tobytes()
        glyphs.append((ord(ch), off, w, h, l, t, adv))
    return asc, desc, glyphs, data

out = ['// generated by overlay/bake_fonts.py - do not edit. Glyphs from Inter / JetBrains Mono (SIL Open Font License).',
       '#pragma once', '#include "vov_font.h"']
for name, file, px, chars in FACES:
    asc, desc, glyphs, data = bake(name, file, px, chars)
    out.append(f'static const uint8_t vov_{name}_bits[{max(len(data),1)}] = {{')
    for i in range(0, len(data), 32):
        out.append('  ' + ','.join(str(b) for b in data[i:i+32]) + ',')
    out.append('};')
    out.append(f'static const VovGlyph vov_{name}_glyphs[{len(glyphs)}] = {{')
    out += [f'  {{{cp},{o},{w},{h},{l},{t},{a}}},' for cp, o, w, h, l, t, a in glyphs]
    out.append('};')
    out.append(f'static const VovFont vov_{name} = {{ vov_{name}_glyphs, {len(glyphs)}, vov_{name}_bits, {asc}, {desc} }};')
    print(name, len(glyphs), 'glyphs', len(data), 'bytes')
(HERE / 'vov_fonts.h').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
